#!/usr/bin/env node
/**
 * Generate docs/template-comparison.md from src/templates.
 *
 * `full` is default plus the full overlay. `js-full` is js-template plus the
 * js-full overlay. Every other directory is listed from its own src tree.
 *
 *   node scripts/generate-template-matrix.mjs           # write the page
 *   node scripts/generate-template-matrix.mjs --check   # fail if it drifted
 */

import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const templatesDir = path.join(root, "src", "templates");
const outFile = path.join(root, "docs", "template-comparison.md");

const COMPOSED = {
  full: { base: "default", overlay: "full" },
  "js-full": { base: "js-template", overlay: "js-full" },
};

function listUnits(template, kind) {
  const dir = path.join(templatesDir, template, "src", kind);
  if (!fs.existsSync(dir)) return [];
  return fs
    .readdirSync(dir)
    .filter((name) => {
      if (name.startsWith(".")) return false;
      if (name.includes(".stories.") || name.includes(".test.")) return false;
      return /\.(tsx|ts|jsx|js)$/.test(name);
    })
    .map((name) => name.replace(/\.(tsx|ts|jsx|js)$/, ""))
    .sort();
}

function unitsFor(template, kind) {
  const composed = COMPOSED[template];
  if (!composed) return listUnits(template, kind);
  return [...new Set([...listUnits(composed.base, kind), ...listUnits(composed.overlay, kind)])].sort();
}

function templates() {
  return fs
    .readdirSync(templatesDir, { withFileTypes: true })
    .filter((entry) => entry.isDirectory())
    .map((entry) => entry.name)
    .sort();
}

function matrix(title, kind, names, templateNames) {
  const header = `| ${title} | ${templateNames.join(" | ")} |`;
  const rule = `| --- | ${templateNames.map(() => ":---:").join(" | ")} |`;
  const rows = names.map((name) => {
    const cells = templateNames.map((template) =>
      unitsFor(template, kind).includes(name) ? "yes" : "",
    );
    return `| \`${name}\` | ${cells.join(" | ")} |`;
  });
  return [header, rule, ...rows].join("\n");
}

function render() {
  const templateNames = templates();
  const componentNames = [...new Set(templateNames.flatMap((t) => unitsFor(t, "components")))].sort();
  const hookNames = [...new Set(templateNames.flatMap((t) => unitsFor(t, "hooks")))].sort();

  return `# Template comparison

Generated by \`scripts/generate-template-matrix.mjs\` from \`src/templates\`.
Do not edit this file by hand. Run \`npm run templates:matrix\` and commit the
result. CI runs \`npm run templates:matrix:check\` and fails if the page
drifted from the tree.

\`full\` is the \`default\` component and hook set plus the \`src/templates/full\`
overlay. \`js-full\` is \`js-template\` plus the \`src/templates/js-full\` overlay.
That matches how the CLI scaffolds those starters (see the Templates section
of the README).

Story files (\`*.stories.*\`) are not components and are omitted.

## Components

${matrix("Component", "components", componentNames, templateNames)}

## Hooks

${matrix("Hook", "hooks", hookNames, templateNames)}
`;
}

const next = render();
const check = process.argv.includes("--check");

if (check) {
  const current = fs.existsSync(outFile) ? fs.readFileSync(outFile, "utf8") : "";
  if (current !== next) {
    console.error(
      "docs/template-comparison.md is out of date. Run: npm run templates:matrix",
    );
    process.exit(1);
  }
  console.log("docs/template-comparison.md matches src/templates");
} else {
  fs.mkdirSync(path.dirname(outFile), { recursive: true });
  fs.writeFileSync(outFile, next);
  console.log(`wrote ${path.relative(root, outFile)}`);
}
